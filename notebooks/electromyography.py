@app.cell
def _(butter, np, sosfiltfilt):
    def linear_envelope(x, freq=1000, fc_bp=[10, 400], fc_lp=8):
        """Calculate the linear envelope of a signal.

        Parameters
        ----------
        x     : 1D array_like
                raw signal
        freq  : number
                sampling frequency
        fc_bp : list [fc_h, fc_l], optional
                cutoff frequencies for the band-pass filter (in Hz)
        fc_lp : number, optional
                cutoff frequency for the low-pass filter (in Hz)

        Returns
        -------
        x     : 1D array_like
                linear envelope of the signal

        Notes
        -----
        Butterworth filters use N=2 prototypes and SOS forward-backward filtering.
        Effective orders are eight for band-pass and four for low-pass filtering.
        This zero-phase operation is noncausal and intended for offline data.

        See this notebook [1]_.

        References
        ----------
        .. [1] electromyography.py

        """
        if np.size(fc_bp) == 2:
            _sos = butter(2, fc_bp, btype='bandpass', fs=freq, output='sos')
            x = sosfiltfilt(_sos, x)
        if np.size(fc_lp) == 1:
            x = abs(x)
            _sos = butter(2, fc_lp, btype='lowpass', fs=freq, output='sos')
            x = sosfiltfilt(_sos, x)
        return x

    return (linear_envelope,)


